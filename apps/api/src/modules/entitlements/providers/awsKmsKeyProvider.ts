import crypto from 'node:crypto';
import { CreateKeyCommand, GetPublicKeyCommand, KMSClient, SignCommand } from '@aws-sdk/client-kms';
import { prisma } from '../../../lib/prisma';
import type { SigningKeyProvider } from '../keyProvider';

const PROVIDER = 'aws-kms';

function base64url(input: Uint8Array | string): string {
  return Buffer.from(input).toString('base64url');
}

function derSpkiToPem(der: Uint8Array): string {
  const publicKey = crypto.createPublicKey({ key: Buffer.from(der), format: 'der', type: 'spki' });
  return publicKey.export({ type: 'spki', format: 'pem' }).toString();
}

/**
 * Production-acceptable provider: the RSA private key is generated by and never leaves
 * AWS KMS (asymmetric SIGN_VERIFY, RSA_2048). Signing is a KMS API call, not a local
 * `crypto` operation — closes the gap documented in docs/security/entitlement-signing.md.
 * `client` is injectable so tests can supply a fake KMSClient without real AWS calls.
 */
export class AwsKmsKeyProvider implements SigningKeyProvider {
  constructor(private readonly client: Pick<KMSClient, 'send'> = new KMSClient({})) {}

  async getActiveKey(): Promise<{ keyId: string; publicKeyPem: string }> {
    const existing = await prisma.signingKey.findFirst({ where: { status: 'ACTIVE', provider: PROVIDER } });
    if (existing) return { keyId: existing.id, publicKeyPem: existing.publicKeyPem };
    return this.createAndStoreKey();
  }

  async sign(keyId: string, claims: Record<string, unknown>): Promise<string> {
    const header = { alg: 'RS256', typ: 'JWT', kid: keyId };
    const signingInput = `${base64url(JSON.stringify(header))}.${base64url(JSON.stringify(claims))}`;

    const result = await this.client.send(
      new SignCommand({
        KeyId: keyId,
        Message: Buffer.from(signingInput),
        MessageType: 'RAW',
        SigningAlgorithm: 'RSASSA_PKCS1_V1_5_SHA_256',
      })
    );
    if (!result.Signature) throw new Error(`KMS returned no signature for key '${keyId}'.`);
    return `${signingInput}.${base64url(result.Signature)}`;
  }

  async getPublicKey(keyId: string): Promise<string | undefined> {
    const cached = await prisma.signingKey.findUnique({ where: { id: keyId } });
    if (cached) return cached.publicKeyPem;

    const pub = await this.client.send(new GetPublicKeyCommand({ KeyId: keyId }));
    if (!pub.PublicKey) return undefined;
    return derSpkiToPem(pub.PublicKey);
  }

  async rotate(): Promise<{ keyId: string; publicKeyPem: string }> {
    await prisma.signingKey.updateMany({
      where: { status: 'ACTIVE', provider: PROVIDER },
      data: { status: 'ROTATED', rotatedAt: new Date() },
    });
    return this.createAndStoreKey();
  }

  private async createAndStoreKey(): Promise<{ keyId: string; publicKeyPem: string }> {
    const created = await this.client.send(
      new CreateKeyCommand({
        KeyUsage: 'SIGN_VERIFY',
        KeySpec: 'RSA_2048',
        Description: 'FormCoach entitlement signing key',
      })
    );
    const keyId = created.KeyMetadata?.KeyId;
    if (!keyId) throw new Error('KMS CreateKey did not return a KeyId.');

    const pub = await this.client.send(new GetPublicKeyCommand({ KeyId: keyId }));
    if (!pub.PublicKey) throw new Error(`KMS GetPublicKey returned no key material for '${keyId}'.`);
    const publicKeyPem = derSpkiToPem(pub.PublicKey);

    await prisma.signingKey.create({
      data: { id: keyId, publicKeyPem, privateKeyPem: null, algorithm: 'RS256', provider: PROVIDER },
    });
    return { keyId, publicKeyPem };
  }
}
